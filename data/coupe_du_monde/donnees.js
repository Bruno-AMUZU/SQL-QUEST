// --- Conversion en lignes ---------------------------------------------------
const idPays = new Map(pays.map(([code], i) => [code, i + 1]));
const id = (code) => {
  if (code === null) return null;
  if (!idPays.has(code)) throw new Error(`Code pays inconnu : ${code}`);
  return idPays.get(code);
};

export default {
  pays: pays.map(([code, nom, continent], i) => [i + 1, nom, continent, code]),
  editions: editions.map(([annee, hote, coHote, v, f, t, score, equipes, buts]) =>
    [annee, id(hote), id(coHote), id(v), id(f), id(t), score, equipes, buts]),
  joueurs: joueurs.map(([nom, p, poste], i) => [i + 1, nom, id(p), poste]),
  buteurs: joueurs.flatMap(([, , , buts], i) =>
    Object.entries(buts).map(([annee, n]) => [i + 1, Number(annee), n])),
};
